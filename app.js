function translate(key, values = {}) {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

function getSpeechRecognitionConstructor() {
  return window.SpeechRecognition || window.webkitSpeechRecognition || null;
}

function createSpeakingButton(labelKey, className, handler) {
  const button = document.createElement("button");
  button.className = className;
  button.type = "button";
  button.textContent = translate(labelKey);
  button.addEventListener("click", handler);
  return button;
}

function renderSpeakingPhrases() {
  const list = document.querySelector("#speaking-list");
  const supportMessage = document.querySelector("#speech-support");
  const recognitionAvailable = Boolean(getSpeechRecognitionConstructor());
  const playbackAvailable = "speechSynthesis" in window
    && "SpeechSynthesisUtterance" in window;

  list.setAttribute("aria-label", translate("speakingListLabel"));
  list.replaceChildren();

  speakingPhrases.forEach((phrase, index) => {
    const card = document.createElement("article");
    card.className = "speaking-card";
    card.dataset.phraseIndex = index;

    const content = document.createElement("div");
    content.className = "speaking-phrase-content";
    const english = document.createElement("h3");
    english.className = "speaking-english";
    english.lang = "en-CA";
    english.dir = "ltr";
    english.textContent = phrase.english;
    const spanish = document.createElement("p");
    spanish.className = "speaking-spanish";
    spanish.lang = "es";
    spanish.textContent = phrase.spanish;
    content.append(english, spanish);

    const actions = document.createElement("div");
    actions.className = "speaking-actions";
    const listenButton = createSpeakingButton("listenButton", "speech-button listen-button", () => {
      playPhrase(phrase.english);
    });
    listenButton.disabled = !playbackAvailable;
    listenButton.setAttribute("aria-label", `${translate("listenButton")}: ${phrase.english}`);

    const speakButton = createSpeakingButton("speakButton", "speech-button speak-button", () => {
      recognizePhrase(index, card);
    });
    speakButton.disabled = !recognitionAvailable;
    speakButton.setAttribute("aria-label", `${translate("speakButton")}: ${phrase.english}`);
    actions.append(listenButton, speakButton);

    const result = document.createElement("div");
    result.className = "speech-result";
    result.hidden = true;
    result.setAttribute("aria-live", "polite");

    card.append(content, actions, result);
    list.append(card);
  });

  supportMessage.textContent = !recognitionAvailable
    ? translate("speechNotSupported")
    : !playbackAvailable
      ? translate("listenUnavailable")
      : translate("speechReady");
}

function playPhrase(phrase) {
  if (!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
    document.querySelector("#speech-support").textContent = translate("listenUnavailable");
    return;
  }

  window.speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(phrase);
  utterance.lang = "en-CA";
  utterance.rate = 0.88;
  window.speechSynthesis.speak(utterance);
}

function normalizeSpeech(text) {
  return text.toLowerCase()
    .replace(/[.,!?;:'"()\-]/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function phraseMatches(phrase, recognized) {
  const expected = normalizeSpeech(phrase);
  const actual = normalizeSpeech(recognized);

  if (expected === "my name is") {
    return actual === expected || actual.startsWith(`${expected} `);
  }

  return actual === expected;
}

function showSpeechResult(card, recognized, messageKey, values = {}) {
  const result = card.querySelector(".speech-result");
  result.replaceChildren();
  result.hidden = false;

  if (recognized) {
    const label = document.createElement("span");
    label.className = "recognized-label";
    label.textContent = translate("recognizedLabel");
    const text = document.createElement("bdi");
    text.className = "recognized-text";
    text.lang = "en-CA";
    text.dir = "ltr";
    text.textContent = recognized;
    result.append(label, text);
  }

  const feedback = document.createElement("p");
  feedback.className = "speech-feedback";
  feedback.textContent = translate(messageKey, values);
  result.append(feedback);
}

function releaseRecognition(recognition) {
  if (activeRecognition !== recognition) {
    return;
  }

  activeRecognition = null;
  document.querySelectorAll(".speaking-card").forEach((card) => {
    const button = card.querySelector(".speak-button");
    const result = card.querySelector(".speech-result");
    const phrase = speakingPhrases[Number(card.dataset.phraseIndex)];
    button.disabled = !getSpeechRecognitionConstructor();
    button.textContent = result && !result.hidden && result.querySelector(".recognized-text")
      ? translate("repeatButton")
      : translate("speakButton");
    button.setAttribute(
      "aria-label",
      `${button.textContent}: ${phrase.english}`,
    );
  });
}

function recognitionErrorMessage(error) {
  const messages = {
    "not-allowed": "speechMicDenied",
    "service-not-allowed": "speechMicDenied",
    "audio-capture": "speechNoMicrophone",
    network: "speechNetworkError",
    "no-speech": "speechNoSpeech",
  };
  return messages[error] || "speechGenericError";
}

function recognizePhrase(index, card) {
  if (activeRecognition) {
    return;
  }

  const Recognition = getSpeechRecognitionConstructor();
  if (!Recognition) {
    document.querySelector("#speech-support").textContent = translate("speechNotSupported");
    return;
  }

  const supportMessage = document.querySelector("#speech-support");
  const speakButton = card.querySelector(".speak-button");
  const recognition = new Recognition();
  recognition.lang = "en-CA";
  recognition.continuous = false;
  recognition.interimResults = false;
  recognition.maxAlternatives = 1;
  activeRecognition = recognition;
  document.querySelectorAll(".speak-button").forEach((button) => {
    button.disabled = true;
  });
  speakButton.textContent = translate("speechListening");
  supportMessage.textContent = translate("speechListening");

  recognition.onresult = (event) => {
    if (activeRecognition !== recognition) {
      return;
    }

    const alternative = event.results
      && event.results[0]
      && event.results[0][0];
    const recognized = alternative && alternative.transcript
      ? alternative.transcript.trim()
      : "";
    if (!recognized) {
      showSpeechResult(card, "", "speechNoMatch");
      supportMessage.textContent = translate("speechNoMatch");
      return;
    }

    const matches = phraseMatches(speakingPhrases[index].english, recognized);
    showSpeechResult(
      card,
      recognized,
      matches ? "speechMatched" : "speechTryAgain",
      matches ? {} : { text: recognized },
    );
    supportMessage.textContent = matches
      ? translate("speechMatched")
      : translate("speechTryAgain", { text: recognized });
    speakButton.textContent = translate("repeatButton");
  };

  recognition.onerror = (event) => {
    if (activeRecognition !== recognition || event.error === "aborted") {
      return;
    }

    const message = recognitionErrorMessage(event.error);
    showSpeechResult(card, "", message);
    supportMessage.textContent = translate(message);
  };

  recognition.onend = () => {
    releaseRecognition(recognition);
    supportMessage.textContent = translate("speechReady");
  };

  try {
    recognition.start();
  } catch (error) {
    releaseRecognition(recognition);
    const message = error.name === "NotAllowedError" ? "speechMicDenied" : "speechGenericError";
    showSpeechResult(card, "", message);
    supportMessage.textContent = translate(message);
  }
}

function cancelActiveRecognition() {
  if (!activeRecognition) {
    return;
  }

  const recognition = activeRecognition;
  activeRecognition = null;
  recognition.onresult = null;
  recognition.onerror = null;
  recognition.onend = null;
  recognition.abort();
}

function updateLanguage() {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
  document.querySelector("#page-description").setAttribute("content", translate("description"));

  for (const element of document.querySelectorAll("[data-i18n]")) {
    const key = element.dataset.i18n;
    element.textContent = translations[language][key];
  }

  document.querySelector(".main-nav").setAttribute("aria-label", translate("navLabel"));
  document.querySelector(".speech-note").setAttribute("aria-label", translate("speechInfoLabel"));
  optionsElement.setAttribute("aria-label", translate("answerChoices"));
  progress.setAttribute("aria-label", translate("progressLabel"));
  cancelActiveRecognition();
  renderSpeakingPhrases();
  const nextLanguage = { en: "es", es: "fa", fa: "fr", fr: "en" }[language];
  const nextLanguageLabel = {
    en: "changeLanguageToSpanish",
    es: "changeLanguageToPersian",
    fa: "changeLanguageToFrench",
    fr: "changeLanguageToEnglish",
  }[language];
  languageToggle.innerHTML = `${nextLanguage.toUpperCase()} <span aria-hidden="true">↗</span>`;
  languageToggle.setAttribute("aria-label", translate(nextLanguageLabel));
  updateScore();

  if (quizCard.querySelector(".quiz-complete")) {
    renderCompletion();
  } else {
    renderQuestion();
  }
}

function updateScore() {
  const completedQuestions = questionIndex + (answered ? 1 : 0);
  scoreElement.textContent = `${score} / ${quizQuestions.length}`;
  questionCount.textContent = translate("questionCount", {
    current: Math.min(questionIndex + 1, quizQuestions.length),
    total: quizQuestions.length,
  });
  progress.setAttribute("aria-valuenow", completedQuestions);
  progressFill.style.width = `${(completedQuestions / quizQuestions.length) * 100}%`;
}

function renderQuestion() {
  const question = quizQuestions[questionIndex];
  questionElement.textContent = question.question[language];
  nextButton.hidden = true;
  nextButton.querySelector("[data-i18n]").textContent = translate(
    questionIndex === quizQuestions.length - 1 ? "tryAgain" : "nextQuestion",
  );

  optionsElement.replaceChildren();
  question.options.forEach((option, index) => {
    const button = document.createElement("button");
    button.className = "quiz-option";
    button.type = "button";
    button.textContent = option;
    if (answered) {
      button.disabled = true;
      if (index === question.answer) {
        button.classList.add("is-correct");
      } else if (index === selectedAnswer) {
        button.classList.add("is-incorrect");
      }
    } else {
      button.addEventListener("click", () => selectAnswer(index));
    }
    optionsElement.append(button);
  });

  updateQuestionFeedback();
  updateScore();
}

function updateQuestionFeedback() {
  if (!answered) {
    feedbackElement.textContent = "";
    return;
  }

  const question = quizQuestions[questionIndex];
  feedbackElement.textContent = selectedAnswer === question.answer
    ? translate("quizCorrect", { explanation: question.explanation[language] })
    : translate("quizIncorrect", {
      answer: question.options[question.answer],
      explanation: question.explanation[language],
    });
  nextButton.hidden = false;
}

function selectAnswer(selectedIndex) {
  if (answered) {
    return;
  }
  answered = true;
  selectedAnswer = selectedIndex;

  const question = quizQuestions[questionIndex];
  const isCorrect = selectedIndex === question.answer;
  const buttons = optionsElement.querySelectorAll(".quiz-option");

  buttons.forEach((button, index) => {
    button.disabled = true;
    if (index === question.answer) {
      button.classList.add("is-correct");
    } else if (index === selectedIndex) {
      button.classList.add("is-incorrect");
    }
  });

  if (isCorrect) {
    score += 1;
  }

  updateQuestionFeedback();
  updateScore();
}

function renderCompletion() {
  questionIndex = quizQuestions.length;
  questionCount.textContent = translate("questionCount", {
    current: quizQuestions.length,
    total: quizQuestions.length,
  });
  progress.setAttribute("aria-valuenow", quizQuestions.length);
  progressFill.style.width = "100%";
  quizCard.innerHTML = `
    <div class="quiz-complete">
      <span class="completion-mark" aria-hidden="true">✳</span>
      <h3>${translate("completionTitle")}</h3>
      <p>${translate("completionScore", { score, total: quizQuestions.length })}</p>
      <p>${translate("completionEncouragement")}</p>
      <button class="button button-dark quiz-next" id="quiz-restart" type="button">
        <span>${translate("tryAgain")}</span><span aria-hidden="true">↻</span>
      </button>
    </div>
  `;
  document.querySelector("#quiz-restart").addEventListener("click", restartQuiz);
}

function advanceQuestion() {
  if (questionIndex === quizQuestions.length - 1) {
    renderCompletion();
    return;
  }

  questionIndex += 1;
  answered = false;
  selectedAnswer = null;
  renderQuestion();
}

function restartQuiz() {
  questionIndex = 0;
  score = 0;
  answered = false;
  selectedAnswer = null;
  quizCard.innerHTML = `
    <div class="quiz-card-top">
      <span class="quiz-label" data-i18n="quickQuiz"></span>
      <span class="question-count" id="question-count"></span>
    </div>
    <p class="quiz-question" id="quiz-question"></p>
    <div class="quiz-options" id="quiz-options" role="group"></div>
    <p class="quiz-feedback" id="quiz-feedback" aria-live="assertive"></p>
    <button class="button button-dark quiz-next" id="quiz-next" type="button" hidden>
      <span data-i18n="nextQuestion"></span><span aria-hidden="true">→</span>
    </button>
  `;

  initializeQuizElements();
  updateLanguage();
}

